 reason VARCHAR(32) NOT NULL CHECK(reason IN ('BASELINE_DRAFT','BASELINE_PUBLISHED','BASELINE_TEMPLATE','MANUAL_DRAFT','PUBLISH','RESTORE_BACKUP','RESTORE')),
 source_revision BIGINT NOT NULL,
 source_version_id BIGINT,
 operation_id VARCHAR(36),
 created_by BIGINT NOT NULL,
 creator_name VARCHAR(80) NOT NULL,
 activity_log_id BIGINT REFERENCES activity_log(id) ON DELETE SET NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(page_id,operation_id,reason)
);
CREATE INDEX page_versions_target ON page_versions(page_id,id);
CREATE TABLE page_version_media (
 version_id BIGINT NOT NULL REFERENCES page_versions(id) ON DELETE CASCADE,
 media_id BIGINT NOT NULL REFERENCES media(id),
 PRIMARY KEY(version_id,media_id)
);
CREATE INDEX page_version_media_lookup ON page_version_media(media_id,version_id);
CREATE TABLE page_template_versions (
