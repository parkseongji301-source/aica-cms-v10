CREATE TABLE media (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(200) NOT NULL, alt VARCHAR(300) NOT NULL DEFAULT '',
 mime VARCHAR(40) NOT NULL, width INTEGER NOT NULL, height INTEGER NOT NULL,
 byte_size BIGINT NOT NULL, data BLOB NOT NULL,
 owner_id BIGINT NOT NULL REFERENCES users(id), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE post_media (
 post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 media_id BIGINT NOT NULL REFERENCES media(id), sort_order INTEGER NOT NULL,
 PRIMARY KEY(post_id, media_id)
);
CREATE TABLE post_publications (
 post_id BIGINT PRIMARY KEY REFERENCES posts(id) ON DELETE CASCADE,
 title VARCHAR(200) NOT NULL, content VARCHAR(20000) NOT NULL,
 category_id BIGINT REFERENCES categories(id), revision BIGINT NOT NULL,
 published_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE post_publication_media (
 post_id BIGINT NOT NULL REFERENCES post_publications(post_id) ON DELETE CASCADE,
 media_id BIGINT NOT NULL REFERENCES media(id), sort_order INTEGER NOT NULL,
 PRIMARY KEY(post_id, media_id)
);
CREATE TABLE site_pages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(200) NOT NULL, slug VARCHAR(100) NOT NULL UNIQUE, sections_json CLOB NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','PRIVATE')),
 revision BIGINT NOT NULL DEFAULT 0, author_id BIGINT NOT NULL REFERENCES users(id),
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE page_publications (
 page_id BIGINT PRIMARY KEY REFERENCES site_pages(id) ON DELETE CASCADE,
 title VARCHAR(200) NOT NULL, slug VARCHAR(100) NOT NULL UNIQUE, sections_json CLOB NOT NULL,
 revision BIGINT NOT NULL, published_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE page_media (
 page_id BIGINT NOT NULL REFERENCES site_pages(id) ON DELETE CASCADE,
 media_id BIGINT NOT NULL REFERENCES media(id), published BOOLEAN NOT NULL,
 PRIMARY KEY(page_id, media_id, published)
);
CREATE TABLE site_menus (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 label VARCHAR(80) NOT NULL, kind VARCHAR(16) NOT NULL CHECK (kind IN ('PAGE','CATEGORY','LINK')),
 target_id BIGINT, url VARCHAR(1000) NOT NULL DEFAULT '',
 sort_order INTEGER NOT NULL DEFAULT 0, visible BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE site_links (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 label VARCHAR(80) NOT NULL, url VARCHAR(1000) NOT NULL, sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE site_settings (
 setting_key VARCHAR(80) PRIMARY KEY, setting_value VARCHAR(2000) NOT NULL
);
